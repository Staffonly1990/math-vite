/** Сколько всего чисел в примере (терм ×/÷ считается за два числа) */
export type NumbersCount = 2 | 3 | 4;

/**
 * Что отрабатывает этап лестницы:
 *   '+'  — только сложение;
 *   '-'  — есть вычитание (сложение уже освоено);
 *   'big' — двузначные ±: операнды 11..99, знаки смешаны;
 *   '*'  — ровно один ×-терм внутри +/− (на 2 числах — чистая таблица);
 *   '/'  — ровно один ÷-терм (на последнем этапе допустим и ×);
 *   'all' — финальный микс: ± до 99 + ×/÷-термы.
 */
export type StageFocus = '+' | '-' | 'big' | '*' | '/' | 'all';

export interface DifficultyConfig {
  /** Сколько всего чисел в примере */
  numbers: NumbersCount;
  /** Отрабатываемая ось этапа */
  focus: StageFocus;
  /** Потолок слагаемых/вычитаемых, включительно */
  addMax: number;
  /** Потолок множителей/делителей — произведения не «баснословные» */
  factorMax: number;
}

/**
 * Математическая лесница «знак × количество чисел» (школьный порядок,
 * внутри каждого знака числа растут 2 → 3 → 4):
 *   1–3    +(2/3/4) — числа 1..9
 *   4–6    −(2/3/4) — числа 1..9, минимум один минус
 *   7–9    двузначные ±(2/3/4) — числа 11..99
 *   10     ×(2) чистая таблица — множители 2..9
 *   11–12  ×(3/4) — ×-терм внутри +/−, слагаемые снова 1..9
 *   13     ÷(2) чистая таблица — деление нацело по построению
 *   14–15  ÷(3/4) — ÷-терм внутри +/−, на этапе 15 допустим и ×
 *   16+    финальный микс — ± до 99 и ×/÷-термы в одном примере.
 * ×/÷ никогда не цепочкой — максимум один ×-терм и один ÷-терм на пример.
 */
export function configForLevel(levelNumber: number): DifficultyConfig {
  const level = Math.max(1, Math.floor(levelNumber));

  if (level >= 16) {
    return { numbers: 4, focus: 'all', addMax: 99, factorMax: 9 };
  }

  const block = Math.floor((level - 1) / 3); // 0:'+', 1:'-', 2:'big', 3:'*', 4:'/'
  const numbers = (2 + ((level - 1) % 3)) as NumbersCount;
  const focus = (['+', '-', 'big', '*', '/'] as const)[block];
  const addMax = focus === 'big' ? 99 : 9;
  return { numbers, focus, addMax, factorMax: 9 };
}
